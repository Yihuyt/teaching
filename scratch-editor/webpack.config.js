const EDITOR_PUBLIC_PATH = process.env.EDITOR_PUBLIC_PATH || '/scratch/';

// scratch-storage 的预构建包(dist/web)把自己的 webpack publicPath 硬编码为 "/"，
// 其 fetch-worker chunk 因此永远从站点根加载——teaching 平台把编辑器挂在
// /scratch/ 路径下，必须把嵌套 runtime 的这个值补丁成实际前缀，并把该
// chunk 一并拷进产物(本构建不会自行发出它)。
class NestedPublicPathPlugin {
    apply(compiler) {
        const {sources, Compilation} = compiler.webpack;
        compiler.hooks.thisCompilation.tap('NestedPublicPathPlugin', compilation => {
            compilation.hooks.processAssets.tap(
                {name: 'NestedPublicPathPlugin', stage: Compilation.PROCESS_ASSETS_STAGE_ADDITIONS},
                assets => {
                    for (const name of Object.keys(assets)) {
                        if (!name.endsWith('.js')) continue;
                        const source = assets[name].source();
                        if (typeof source !== 'string') continue;
                        const patched = source.replace(
                            /(__nested_webpack_require_\d+__\.p = )"\/"/g,
                            `$1${JSON.stringify(EDITOR_PUBLIC_PATH)}`
                        );
                        if (patched !== source) {
                            compilation.updateAsset(name, new sources.RawSource(patched));
                        }
                    }
                }
            );
        });
    }
}

